"""Generates every app-icon asset from one geometry, redrawn from the
"Radiant Wi-Fi X" artwork as flat vectors:

  res/drawable/ic_launcher_foreground.xml   adaptive icon, foreground layer
  res/drawable/ic_launcher_monochrome.xml   Android 13+ themed icon
  res/drawable/ic_stat_homora.xml           notification icon (white)
  res/values/ic_launcher_background.xml     background colour
  res/mipmap-anydpi/ic_launcher.xml     adaptive icon definition
  store/icon_512.png, store/icon.svg        Play Store icon (full square)

Run from homora/:  python3 tools/make_icon.py
"""
import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res"

BG = "#0B1630"
BLUE = "#2E8BFF"
WHITE = "#EEF2FA"

# Geometry in the 108x108 adaptive-icon canvas, scaled about the centre so
# everything sits inside the 66 dp safe zone.
K = 0.97
CX, CY = 54.0, 54.0
OX, OY = 0.0, 2.0  # the X's centre sits slightly below the canvas centre
X_STROKE = 7.0 * K
ARC_STROKE = 4.2 * K
DOT_R = 3.8 * K
GAP = 9.5 * K
TIPS = [(-22, -17), (22, -17), (-21, 19), (21, 19)]
ARCS = [(12.4, 26), (20.8, 33), (29.7, 36)]  # (radius, half-angle from vertical, degrees)


def pt(x, y):
    return CX + K * (x + OX), CY + K * (y + OY)


def arms():
    out = []
    for tx, ty in TIPS:
        L = math.hypot(tx, ty)
        sx, sy = pt(tx * GAP / K / L, ty * GAP / K / L)
        ex, ey = pt(tx, ty)
        out.append(f"M{sx:.2f},{sy:.2f} L{ex:.2f},{ey:.2f}")
    return out


def arcs():
    out = []
    for r, a in ARCS:
        t = math.radians(a)
        x1, y1 = pt(-r * math.sin(t), -r * math.cos(t))
        x2, y2 = pt(r * math.sin(t), -r * math.cos(t))
        out.append(f"M{x1:.2f},{y1:.2f} A{r*K:.2f},{r*K:.2f} 0 0,1 {x2:.2f},{y2:.2f}")
    return out


def dot():
    x, y = pt(0, 0)
    return f"M{x - DOT_R:.2f},{y:.2f} a{DOT_R:.2f},{DOT_R:.2f} 0 1,0 {2*DOT_R:.2f},0 a{DOT_R:.2f},{DOT_R:.2f} 0 1,0 {-2*DOT_R:.2f},0 Z"


def vector(color_x, color_arc, size_dp=108, viewport=108, translate=(0, 0)):
    tx, ty = translate
    stroke = lambda d, c, w: (f'        <path android:pathData="{d}" android:strokeColor="{c}" '
                              f'android:strokeWidth="{w:.2f}" android:strokeLineCap="round" />')
    body = [stroke(d, color_x, X_STROKE) for d in arms()] + [stroke(d, color_arc, ARC_STROKE) for d in arcs()]
    body.append(f'        <path android:pathData="{dot()}" android:fillColor="{color_arc}" />')
    return ("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by tools/make_icon.py; edit the script, not this file. -->\n"
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
            f'    <group android:translateX="{tx}" android:translateY="{ty}">\n' + "\n".join(body) + "\n    </group>\n</vector>\n")


def svg(size=512, full_square=True):
    s = size / 108
    stroke = lambda d, c, w: f'<path d="{d}" stroke="{c}" stroke-width="{w:.2f}" stroke-linecap="round" fill="none"/>'
    parts = [f'<rect width="108" height="108" fill="{BG}"/>' if full_square else ""]
    parts += [stroke(d, WHITE, X_STROKE) for d in arms()] + [stroke(d, BLUE, ARC_STROKE) for d in arcs()]
    parts.append(f'<path d="{dot()}" fill="{BLUE}"/>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">'
            + "".join(parts) + "</svg>")


def png(path, size=512, full_square=True):
    """Rasterises the same geometry with Pillow (4x supersampled), round caps drawn as discs."""
    ss = 4
    S = size * ss / 108
    img = Image.new("RGBA", (size * ss, size * ss), BG if full_square else (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    def cap(x, y, w, c):
        r = w * S / 2
        d.ellipse([x * S - r, y * S - r, x * S + r, y * S + r], fill=c)

    for tx, ty in TIPS:
        L = math.hypot(tx, ty)
        sx, sy = pt(tx * GAP / K / L, ty * GAP / K / L)
        ex, ey = pt(tx, ty)
        d.line([sx * S, sy * S, ex * S, ey * S], fill=WHITE, width=round(X_STROKE * S))
        cap(sx, sy, X_STROKE, WHITE)
        cap(ex, ey, X_STROKE, WHITE)
    cx, cy = pt(0, 0)
    for r, a in ARCS:
        rr = r * K
        w = ARC_STROKE
        box = [(cx - rr - w / 2) * S, (cy - rr - w / 2) * S, (cx + rr + w / 2) * S, (cy + rr + w / 2) * S]
        d.arc(box, start=-90 - a, end=-90 + a, fill=BLUE, width=round(w * S))
        for sgn in (-1, 1):
            t = math.radians(a) * sgn
            cap(cx + rr * math.sin(t), cy - rr * math.cos(t), w, BLUE)
    cap(cx, cy, DOT_R * 2, BLUE)
    img.resize((size, size), Image.LANCZOS).save(path)


def main():
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "mipmap-anydpi").mkdir(parents=True, exist_ok=True)
    (RES / "drawable/ic_launcher_foreground.xml").write_text(vector(WHITE, BLUE))
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector("#FF000000", "#FF000000"))
    # Notification icon: crop the 108 canvas to the glyph (about 58 units square).
    (RES / "drawable/ic_stat_homora.xml").write_text(vector("#FFFFFFFF", "#FFFFFFFF", size_dp=24, viewport=60, translate=(-24, -23)))
    (RES / "values/ic_launcher_background.xml").write_text(
        f'<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">{BG}</color>\n</resources>\n')
    (RES / "mipmap-anydpi/ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        '</adaptive-icon>\n')
    store = ROOT / "store"
    store.mkdir(exist_ok=True)
    (store / "icon.svg").write_text(svg())
    png(store / "icon_512.png")
    print("icon assets written")


if __name__ == "__main__":
    main()
